using System.Windows;
using System.Windows.Controls;

namespace Heimdall.App
{
    /// <summary>Applies shared appearance to app-owned windows and generated table editors.</summary>
    public static class ApplicationTheme
    {
        private static bool _initialized;
        #region BEGIN Public
        /// <summary>Enables palette-aware generated column styles before table cells are created.</summary>
        public static readonly DependencyProperty ThemeColumnsProperty = DependencyProperty.RegisterAttached(
            "ThemeColumns", typeof(bool), typeof(ApplicationTheme), new PropertyMetadata(false, ThemeColumnsChanged));
        /// <summary>Reads whether a table uses shared generated editor styles.</summary>
        public static bool GetThemeColumns(DependencyObject target) => (bool)target.GetValue(ThemeColumnsProperty);
        /// <summary>Enables shared generated editor styles for a table.</summary>
        public static void SetThemeColumns(DependencyObject target, bool value) => target.SetValue(ThemeColumnsProperty, value);
        /// <summary>Registers once before any application windows are displayed.</summary>
        public static void Initialize()
        {
            if (_initialized) return;
            _initialized = true;
            EventManager.RegisterClassHandler(typeof(Window), FrameworkElement.LoadedEvent,
                new RoutedEventHandler((sender, args) =>
                {
                    if (sender is not Window window || !ReferenceEquals(args.OriginalSource, window)) return;
                    window.SetResourceReference(Window.BackgroundProperty, "WindowBackgroundBrush");
                    window.SetResourceReference(Window.ForegroundProperty, "PrimaryTextBrush");
                    window.Icon ??= ApplicationBranding.Icon;
                    WindowThemeChrome.Apply(window);
                    AppearanceManager.Attach(window);
                }));
            EventManager.RegisterClassHandler(typeof(UserControl), FrameworkElement.LoadedEvent,
                new RoutedEventHandler((sender, args) =>
                {
                    if (sender is UserControl view && ReferenceEquals(args.OriginalSource, view) &&
                        Heimdall.Application.AppearanceTargets.All.ContainsKey(view.GetType().Name)) AppearanceManager.Attach(view);
                }));
        }
        #endregion END Public
        #region BEGIN private helpers
        private static void ThemeColumnsChanged(DependencyObject target, DependencyPropertyChangedEventArgs args)
        {
            if (target is not DataGrid grid) return;
            grid.AutoGeneratedColumns -= ColumnsGenerated;
            if ((bool)args.NewValue)
            {
                grid.AutoGeneratedColumns += ColumnsGenerated;
                ApplyColumnStyles(grid);
            }
        }
        private static void ColumnsGenerated(object? sender, EventArgs args)
        {
            if (sender is DataGrid grid) ApplyColumnStyles(grid);
        }
        private static void ApplyColumnStyles(DataGrid grid)
        {
            foreach (var column in grid.Columns.OfType<DataGridBoundColumn>())
            {
                if (column is not (DataGridTextColumn or DataGridCheckBoxColumn)) continue;
                var defaultEditor = column is DataGridCheckBoxColumn
                    ? DataGridCheckBoxColumn.DefaultEditingElementStyle : DataGridTextColumn.DefaultEditingElementStyle;
                if (column.ReadLocalValue(DataGridBoundColumn.EditingElementStyleProperty) == DependencyProperty.UnsetValue ||
                    ReferenceEquals(column.EditingElementStyle, defaultEditor))
                    column.EditingElementStyle = (Style)grid.FindResource(column is DataGridCheckBoxColumn ? typeof(CheckBox) : typeof(TextBox));
                if (column is not DataGridCheckBoxColumn ||
                    column.ReadLocalValue(DataGridBoundColumn.ElementStyleProperty) != DependencyProperty.UnsetValue &&
                    !ReferenceEquals(column.ElementStyle, DataGridCheckBoxColumn.DefaultElementStyle)) continue;
                var display = new Style(typeof(CheckBox), (Style)grid.FindResource(typeof(CheckBox)));
                display.Setters.Add(new Setter(UIElement.IsHitTestVisibleProperty, false));
                display.Setters.Add(new Setter(UIElement.FocusableProperty, false));
                display.Setters.Add(new Setter(FrameworkElement.HorizontalAlignmentProperty, HorizontalAlignment.Center));
                column.ElementStyle = display;
            }
        }
        #endregion END private helpers
    }
}
